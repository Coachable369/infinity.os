        assert_eq!(document.bytes(),source);
        panel.generation=GenerationStatus::Complete;
        panel.pending=assistant::Action::ReplaceCompile;
        assistant::write(2,panel);
        assert_eq!(stream_document(&mut document,200).unwrap(),1);
        assert_eq!(document.bytes(),replacement);
        assert!(runtime_repair_state(&assistant::read(2),&document,source,1));
        assert!(!runtime_repair_state(&assistant::read(2),&document,source,2));
        assert_eq!(stream_document(&mut document,300).unwrap(),0);
        let attempt=Attempt {complete:true,compiled:false,diagnostics:diagnostics.to_vec(),
            compiled_revision:document_revision(&document),repairable:true,atomic_replacement:true};
        assert!(queue_repair(request,&attempt,&document,&mut prompt).is_ok());
        panel=assistant::read(2);
        assert_eq!(panel.repair_attempts,2);
        assert!(!panel.permits_generated_launch());
        assert!(panel.runtime_repair);
        assert_eq!(panel.workflow_goal,None);
        panel.generation=GenerationStatus::Complete;assistant::write(2,panel);
        assert!(queue_repair(request,&attempt,&document,&mut prompt).is_err());
        assert_eq!(document.bytes(),replacement);
        assert!(document.insert(b' '));
        let user_edit=document.bytes().to_vec();
