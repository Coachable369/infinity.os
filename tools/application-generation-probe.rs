        panel.source_language=ui::app_assistant::editor_compile_intent::SourceLanguage::Python;
        panel.document_revision=document_revision(&document);
        panel.generation=ui::app_assistant::GenerationStatus::Running;
        panel.argument[..replacement.len()].copy_from_slice(replacement);panel.argument_len=replacement.len();
        assert!(panel.preserves_existing_source());
        ui::app_assistant::write(2,panel);
        assert_eq!(stream_document(&mut document,100_000_000).unwrap(),0);
        assert_eq!(document.bytes(),original);
        panel.generation=ui::app_assistant::GenerationStatus::Complete;
        panel.pending=ui::app_assistant::Action::ReplaceCompile;
        ui::app_assistant::write(2,panel);
