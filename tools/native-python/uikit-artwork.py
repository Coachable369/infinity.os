"""Package production-rendered UIKit states for native Python applications."""
from pathlib import Path
import base64
import os
import subprocess
import zlib
import struct

# ------------------------=
# FUNC: main
# DESC: Derive the reusable Python artwork directly from the production Rust sampler under build-kit authority.
# ------------------=
def main():
    assert os.environ.get("INFINITY_BUILD_KIT_ACTIVE"), "Use ./build-kit run"
    root=Path(__file__).resolve().parents[2]
    executable=root/"build/tools/python-uikit-artwork"
    executable.parent.mkdir(parents=True,exist_ok=True)
    subprocess.run(["rustc","--edition=2021",str(Path(__file__).with_suffix('.rs')),"-o",str(executable)],check=True)
    raw=subprocess.check_output([str(executable)])
    assert len(raw)==9*80*40*3
    data=base64.b64encode(zlib.compress(raw,9)).decode()
    tokens=(root/"assets/ui-design-kit/default/uikit-tokens.bin").read_bytes()
    assert tokens[:8]==b"IUIKIT01" and len(tokens)==64
    names=("canvas","panel","raised","border","text","muted","accent","bright","focus","success","warning","danger","scrim")
    colors={name:f"#{value&0xffffff:06x}" for name,value in zip(names,struct.unpack_from("<13I",tokens,12))}
    destination=root/"sdk/python/infinity_uikit_artwork.py"
    source=(
        '"""Generated by tools/native-python/uikit-artwork.py from the production UIKit sampler."""\n'
        + 'COLORS = '+repr(colors)+'\n' + 'SURFACES = '+repr(data)+'\n')
    if not destination.exists() or destination.read_text()!=source:
        destination.write_text(source)

if __name__ == "__main__":
    main()
