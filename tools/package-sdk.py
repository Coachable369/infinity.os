#!/usr/bin/env python3
"""Build one canonical SDK catalog for native runtime and archive consumers."""
import hashlib
import gzip
import io
import json
import os
from pathlib import Path, PurePosixPath
import tarfile
import zlib

ROOT = Path(__file__).resolve().parents[1]

# ------------------------=
# FUNC: object_id
# DESC: Derives a stable, collision-checked SDK object identity from its public path.
# ------------------=
def object_id(path):
    # Keep durable references valid across the SDK's public namespace rename.
    identity_key = path.replace("/InfinitySDK", "/InfintySDK", 1) if path.startswith("/InfinitySDK") else path
    return b"IFSDK001" + hashlib.sha256(identity_key.encode()).digest()[:8]

# ------------------------=
# FUNC: catalog
# DESC: Validates canonical sources and builds directory, file and digest records.
# ------------------=
def catalog():
    config = json.loads((ROOT / "sdk/distribution/package.json").read_text())
    files = dict(config["files"])
    for target, source in config["trees"].items():
        for item in sorted((ROOT / source).rglob("*")):
            if item.is_file():
                files[str(PurePosixPath(target) / item.relative_to(ROOT / source))] = str(item.relative_to(ROOT))
    records, payloads = [], {}
    for target, source in sorted(files.items()):
        path = PurePosixPath(target)
        if path.is_absolute() or ".." in path.parts or len((config["root"] + "/" + target).encode()) > 95:
            raise ValueError(f"Invalid SDK target: {target}")
        resolved = (ROOT / source).resolve(strict=True)
        if not resolved.is_relative_to(ROOT):
            raise ValueError(f"Source escapes repository: {source}")
        data = resolved.read_bytes()
        payloads[target] = data
        records.append(dict(path=target, source=source, size=len(data), sha256=hashlib.sha256(data).hexdigest()))
    manifest = dict(version=config["version"], root=config["root"], files=records)
    payloads["manifest.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    directories = {config["root"]}
    for target in payloads:
        parent = PurePosixPath(config["root"]) / target
        directories.update(str(p) for p in parent.parents if str(p).startswith(config["root"]))
    entries = [(path, None) for path in sorted(directories)]
    entries += [(config["root"] + "/" + target, data) for target, data in sorted(payloads.items())]
    ids = [object_id(path) for path, _ in entries]
    if len(set(ids)) != len(ids) or len(entries) > 180:
        raise ValueError("SDK namespace identity collision or enumeration capacity exceeded")
    return manifest, payloads, entries

# ------------------------=
# FUNC: write_changed
# DESC: Keeps generated dependency timestamps stable when content is unchanged.
# ------------------=
def write_changed(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)

# ------------------------=
# FUNC: main
# DESC: Produces the native include catalog and an atomically published versioned SDK archive.
# ------------------=
def main():
    if not os.environ.get("INFINITY_BUILD_KIT_ACTIVE"):
        raise SystemExit("Use ./build-kit sdk-package")
    manifest, payloads, entries = catalog()
    sources = {row["path"]: row["source"] for row in manifest["files"]}
    lines = ["// Generated by tools/package-sdk.py; canonical inputs: package.json and source files.",
             "pub static ENTRIES: &[Entry] = &["]
    for path, data in entries:
        ident = ",".join(str(n) for n in object_id(path))
        relative = path.removeprefix(manifest["root"] + "/")
        if data is None:
            value = "None"
        elif relative == "manifest.json":
            value = 'Some(include_bytes!("manifest.json"))'
        else:
            value = 'Some(include_bytes!("../../' + sources[relative] + '"))'
        is_text = data is not None and PurePosixPath(path).suffix in (".md", ".json", ".infinityui", ".py", ".c", ".h")
        crc = zlib.crc32(data) if data is not None else 0
        lines.append(f'    Entry {{ path: b"{path}", id: ObjectId([{ident}]), data: {value}, text: {str(is_text).lower()}, crc: {crc} }},')
    # Built-in shell resources use the same immutable object service, but do not
    # belong in the downloadable SDK or consume writable namespace slots.
    root_id = ",".join(map(str, object_id("/System")))
    lines.append(f'    Entry {{ path: b"/System", id: ObjectId([{root_id}]), data: None, text: false, crc: 0 }},')
    for asset in sorted((ROOT / "sdk/system").iterdir()):
        path = "/System/" + asset.name
        ident = ",".join(map(str, object_id(path)))
        text = str(asset.suffix in (".py", ".txt")).lower()
        lines.append(f'    Entry {{ path: b"{path}", id: ObjectId([{ident}]), data: Some(include_bytes!("../../sdk/system/{asset.name}")), text: {text}, crc: {zlib.crc32(asset.read_bytes())} }},')
    lines.append("];")
    write_changed(ROOT / "build/sdk/manifest.json", payloads["manifest.json"])
    write_changed(ROOT / "build/sdk/catalog.rs", ("\n".join(lines) + "\n").encode())
    archive = ROOT / "builds/InfinitySDK.tar.gz"
    archive.parent.mkdir(exist_ok=True)
    temporary = archive.with_suffix(".tmp")
    with temporary.open("wb") as stream, gzip.GzipFile(filename="", fileobj=stream, mode="wb", mtime=0) as compressed:
        with tarfile.open(fileobj=compressed, mode="w") as tar:
            for relative, data in sorted(payloads.items()):
                info = tarfile.TarInfo("InfinitySDK/" + relative)
                info.size, info.mode, info.mtime = len(data), 0o644, 0
                tar.addfile(info, io.BytesIO(data))
    temporary.replace(archive)
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    write_changed(archive.with_suffix(archive.suffix + ".sha256"), f"{digest}  {archive.name}\n".encode())
    # Retire only the packager's identifiable old generated archive, never an
    # arbitrary file stored under that name. Do so after publishing its successor.
    legacy = archive.with_name("InfintySDK.tar.gz")
    if legacy.is_file() and not legacy.is_symlink():
        with tarfile.open(legacy, "r:gz") as old:
            if json.load(old.extractfile("InfintySDK/manifest.json")).get("root") != "/InfintySDK":
                raise ValueError("Unrecognized legacy SDK archive; not removed")
        legacy.unlink()
        receipt = legacy.with_suffix(".gz.sha256")
        if receipt.is_file() and not receipt.is_symlink() and receipt.read_text().strip().endswith("  InfintySDK.tar.gz"):
            receipt.unlink()
    print(f"SDK {manifest['version']}: {len(payloads)} files, {len(entries)} namespace entries; {archive}")

if __name__ == "__main__":
    main()
